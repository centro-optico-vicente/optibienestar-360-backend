-- ────────────────────────────────────────────────────────────────────────────
-- scripts/db/seed-catalog.sql — renders src/main/resources/db/snapshot/seed-catalog.md: what the
-- migrations themselves seed (row counts per table, plus the codes/names of
-- small catalogs). Run by scripts/db/snapshot.sh against a database that has
-- ONLY migrations applied (never a dev/prod database with real data).
-- ────────────────────────────────────────────────────────────────────────────
SET search_path TO app, public;

WITH
tbl AS (
    SELECT c.relname,
           (SELECT a.attname FROM pg_attribute a
            WHERE a.attrelid = c.oid AND NOT a.attisdropped
              AND a.attname IN ('code', 'name', 'iso_code', 'entity_key', 'key', 'config_key')
            ORDER BY array_position(ARRAY['code', 'iso_code', 'entity_key', 'config_key', 'key', 'name'], a.attname::text)
            LIMIT 1) AS label_col,
           (xpath('/row/n/text()',
                  query_to_xml(format('SELECT count(*) AS n FROM app.%I', c.relname), false, true, '')))[1]::text::int AS n
    FROM pg_class c
    WHERE c.relnamespace = 'app'::regnamespace
      AND c.relkind IN ('r', 'p')
      AND c.relname <> 'flyway_schema_history'
),
labeled AS (
    SELECT t.*,
           CASE WHEN t.label_col IS NOT NULL AND t.n BETWEEN 1 AND 500 THEN
               (xpath('/row/l/text()',
                      query_to_xml(format('SELECT string_agg(%1$I::text, '', '' ORDER BY %1$I::text) AS l FROM app.%2$I',
                                          t.label_col, t.relname), false, true, '')))[1]::text
           END AS labels
    FROM tbl t
)
SELECT '# Seed catalog — data created by migrations' || E'\n\n'
    || '> **GENERATED — do not edit.** Regenerated by `scripts/db/snapshot.sh`. Rows present after applying'
    || ' every migration on an empty database (no dev seeds, no real data); the rows themselves are in [`data.sql`](data.sql).'
    || ' Tables with 0 rows are omitted.'
    || E'\n\n## Row counts\n\n```\n'
    || string_agg(rpad(relname, 48) || lpad(n::text, 6), E'\n' ORDER BY relname) FILTER (WHERE n > 0)
    || E'\n```\n\n## Catalog values (`code`/`name`, tables up to 500 rows)\n\n'
    || COALESCE(string_agg('### ' || relname || ' (`' || label_col || '`, ' || n || E')\n\n'
                           || replace(replace(replace(labels, '&amp;', '&'), '&lt;', '<'), '&gt;', '>'),
                           E'\n\n' ORDER BY relname) FILTER (WHERE labels IS NOT NULL), '_none_')
FROM labeled;
